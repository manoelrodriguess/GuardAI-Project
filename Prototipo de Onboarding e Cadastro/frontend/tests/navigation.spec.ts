import { test, expect, type Page } from "@playwright/test"
import { readFile } from "node:fs/promises"
import { randomInt } from "node:crypto"
const password = "SenhaDeTeste123"
function person(type: "senior" | "caregiver") { return { type, name: `${type === "senior" ? "Pessoa Protegida" : "Responsável"} ${randomInt(100000, 999999)}`, phone: `11${randomInt(100000000, 999999999)}` } }
type Person = ReturnType<typeof person>
async function expectDashboard(page: Page, user: Person) {
  await expect(page).toHaveURL(user.type === "senior" ? /#\/senior\?/ : /#\/care\?/)
  await expect(page.locator(".person b")).toHaveText(user.name)
}
async function register(page: Page, user: Person, consent = true) {
  await page.goto("/")
  await page.getByRole("button", { name: "Cadastrar-se", exact: true }).click()
  await page.getByRole("button", { name: user.type === "senior" ? /Sou idoso/ : /Sou responsável/ }).click()
  await page.getByLabel("Nome completo", { exact: true }).fill(user.name)
  await page.getByLabel("Telefone", { exact: true }).fill(user.phone)
  await expect(page.getByLabel("E-mail", { exact: true })).toHaveCount(0)
  if (user.type === "senior") await page.getByLabel("Data de nascimento", { exact: true }).fill("1952-04-15")
  await page.getByLabel("Senha", { exact: true }).fill(password)
  await page.getByLabel("Confirme a senha", { exact: true }).fill(password)
  if (user.type === "senior" && consent) await page.getByRole("checkbox").check()
  await page.getByRole("button", { name: "Criar minha conta", exact: true }).click()
  await expectDashboard(page, user)
  if (user.type === "senior") expect((await (await page.request.get("/api/auth/me")).json()).birth_date).toBe("1952-04-15")
}
async function menu(page: Page, label: string | RegExp) {
  await page.getByRole("button", { name: "Menu", exact: true }).click()
  await page.getByRole("button", { name: label, exact: typeof label === "string" }).click()
}
async function back(page: Page) { await page.getByRole("button", { name: "Voltar", exact: true }).click() }
async function logout(page: Page) {
  await menu(page, "Sair da conta")
  await expect(page.getByRole("button", { name: "Cadastrar-se", exact: true })).toBeVisible()
}
async function login(page: Page, user: Person) {
  await page.getByRole("button", { name: "Entrar", exact: true }).click()
  await page.getByLabel("Telefone", { exact: true }).fill(user.phone)
  await page.getByLabel("Senha", { exact: true }).fill(password)
  await page.getByRole("button", { name: "Entrar", exact: true }).click()
  await expectDashboard(page, user)
}

